// Builds sites.generated.js from the app's src/mediaTypes.js, so the
// extension recognises the same pages, codes and chapters as the app's
// tabs and reads them with the same scripts. Run it after changing
// mediaTypes.js:
//
//   node extension/build-sites.mjs
//
// The site addresses aren't in the output: mediaTypes.js is loaded with
// placeholder sites, and the extension swaps in the ones set on its
// options page when it builds the patterns (rules.js). The page scripts
// become real functions (extensions can't run code from strings).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = fs.readFileSync(path.join(here, '..', 'src', 'mediaTypes.js'), 'utf8');

// One placeholder per site setting (the same names as app.config.js's
// extra), swapped for the real sites at run time.
export const PLACEHOLDERS = {
  mangaSiteUrl: 'https://manga-site-1.invalid',
  mangaSite2Url: 'https://manga-site-2.invalid',
  animeSiteUrl: 'https://anime-site-1.invalid',
  manhwaSiteUrl: 'https://manhwa-site-1.invalid',
  manhwaSite2Url: 'https://manhwa-site-2.invalid',
  manhwaSite3Url: 'https://manhwa-site-3.invalid',
};

const code = source
  .replace("import Constants from 'expo-constants';", 'const Constants = { expoConfig: { extra: __EXTRA } };')
  .replace(/^export /gm, '');
// eslint-disable-next-line no-new-func
const { MEDIA_TYPE_LIST } = new Function('__EXTRA', `${code}\nreturn { MEDIA_TYPES, MEDIA_TYPE_LIST };`)(PLACEHOLDERS);

// A function's source as an expression.
function fn(f) {
  if (!f) return 'null';
  const text = f.toString();
  return /^(async\s+)?(function\b|\(|[A-Za-z_$][\w$]*\s*=>)/.test(text) ? text : `function ${text}`;
}

// A page script (a string the app injects) as a function body.
function script(js) {
  if (!js) return 'null';
  return `function () {${js}}`;
}

function sourceEntry(type, src, name) {
  return `      {
        name: ${JSON.stringify(name || null)},
        pattern: ${JSON.stringify(src.urlRegex.source)},
        flags: ${JSON.stringify(src.urlRegex.flags)},
        extractId: ${fn(src.extractId)},
        extractProgress: ${fn(src.extractProgress || type.extractProgress)},
        seriesFromPage: ${!!src.seriesFromPage},
        interstitialKeywords: ${JSON.stringify(src.interstitialKeywords || type.interstitialKeywords || null)},
        extractMetadata: ${script(src.extractMetadataJs)},
      }`;
}

const types = MEDIA_TYPE_LIST.map((type) => {
  const sources = type.sources
    ? type.sources.map((s) => sourceEntry(type, s, s.name))
    : [sourceEntry(type, type, type.siteName || null), ...(type.extraSources || []).map((s) => sourceEntry(type, s, s.name))];
  return `  {
    key: ${JSON.stringify(type.key)},
    label: ${JSON.stringify(type.label)},
    sources: [
${sources.join(',\n')}
    ],
  }`;
});

const out = `// GENERATED by build-sites.mjs from src/mediaTypes.js — don't edit by
// hand; change mediaTypes.js and run \`node extension/build-sites.mjs\`.
// Site addresses are placeholders (PLACEHOLDERS below), swapped for the
// ones set on the options page by rules.js.
/* eslint-disable */
self.MT_PLACEHOLDERS = ${JSON.stringify(PLACEHOLDERS, null, 2)};
self.MT_TYPES = [
${types.join(',\n')}
];
`;
fs.writeFileSync(path.join(here, 'sites.generated.js'), out);
console.log(`Wrote sites.generated.js (${MEDIA_TYPE_LIST.length} types).`);
